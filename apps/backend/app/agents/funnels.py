    async def _generate_recommendations(
        self,
        llm: Any,
        domain: str,
        objective: str,
        analysis: dict[str, Any],
        bottlenecks: list[dict[str, Any]],
        disclaimer: str,
    ) -> list[dict[str, Any]]:
        """Synthesize prioritized growth recommendations."""
        default_recs = [
            {
                "category": "Quick Win",
                "title": "Tối ưu trang Thank You Page với One-Time Offer (OTO)",
                "description": "Thêm ưu đãi giảm giá độc quyền cho sản phẩm tự học trong 15 phút ngay sau khi tải tài liệu.",
                "impact": "High",
                "effort": "Low",
            },
            {
                "category": "Core Funnel",
                "title": "Kích hoạt chuỗi Email Nurture 5 ngày chuẩn SOAP Opera",
                "description": "Gửi câu chuyện vượt khó và case study chuyển hóa trước khi mở bán gói Coach.",
                "impact": "High",
                "effort": "Medium",
            },
            {
                "category": "High-Ticket Scaling",
                "title": "Triển khai mẫu khảo sát chọn lọc (Application Funnel)",
                "description": "Yêu cầu ứng viên điền bảng hỏi 4 câu trước khi được đặt lịch tư vấn gói Đồng hành chuyên sâu.",
                "impact": "High",
                "effort": "Medium",
            },
            {
                "category": "Pricing Strategy",
                "title": "Thử nghiệm chính sách thanh toán chia nhỏ (Split-Pay)",
                "description": "Cho phép thanh toán 2 đợt đối với gói Coach để giảm rào cản chi tiêu ban đầu.",
                "impact": "Medium",
                "effort": "Low",
            },
        ]

        if llm is None:
            return default_recs

        prompt_system = (
            "Bạn là chuyên gia cố vấn tăng trưởng và định giá phễu (Growth & Pricing Advisor). "
            "Hãy đề xuất 3-5 giải pháp tối ưu chuyển đổi, định giá và mở rộng phễu bán hàng. "
            "Trả về JSON danh sách với cấu trúc: {'recommendations': [{'category': '...', 'title': '...', 'description': '...', 'impact': 'High/Medium'}]}"
        )
        user_prompt = (
            f"Lĩnh vực: {domain}\n"
            f"Mục tiêu: {objective}\n"
            f"Dữ liệu phân tích: {json.dumps(analysis, ensure_ascii=False)}\n"
            f"Điểm nghẽn: {json.dumps(bottlenecks, ensure_ascii=False)}"
        )

        messages = [
            {"role": "system", "content": prompt_system},
            {"role": "user", "content": user_prompt},
        ]

        raw_llm = await _invoke_llm(llm, messages, agent=self.agent)
        if raw_llm:
            try:
                clean_json = raw_llm.strip()
                if "```json" in clean_json:
                    clean_json = clean_json.split("```json")[1].split("```")[0]
                elif "```" in clean_json:
                    clean_json = clean_json.split("```")[1].split("```")[0]
                parsed = json.loads(clean_json.strip())
                if isinstance(parsed, dict) and "recommendations" in parsed:
                    recs = parsed["recommendations"]
                    if isinstance(recs, list) and len(recs) >= 2:
                        return recs
            except Exception as e:
                logger.debug("Could not parse LLM growth recommendations: %s", e)

        return default_recs

