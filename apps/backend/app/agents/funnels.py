def _detect_compliance_domain(domain: str, context_text: str = "") -> Optional[str]:
    """Detect sensitive regulatory categories requiring mandatory compliance guards."""
    combined = f"{domain} {context_text}".lower()
    for kw in _HEALTH_KEYWORDS:
        if kw in combined:
            return "health"
    for kw in _FINANCE_KEYWORDS:
        if kw in combined:
            return "finance"
    return None


