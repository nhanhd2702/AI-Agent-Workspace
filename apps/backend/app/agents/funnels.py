class FunnelsAgent(BaseWorkerAgent):
    """Worker Agent that architectures 7-section conversion funnels with compliance guards."""

    def __init__(
        self,
        agent: Optional[Agent] = None,
        llm: Optional[Any] = None,
        llm_router: Optional[LlmRouter] = None,
        brand_profile: Optional[BrandProfile | dict[str, Any]] = None,
        session_factory: Optional[Any] = None,
        db: Optional[Any] = None,
        **kwargs: Any,
    ) -> None:
        synth_agent = agent or Agent(
            id="agent-funnels-agent",
            name="FunnelsAgent",
            display_name="Funnels Strategist",
            role="Funnels Strategist",
            default_model="gemini-2.5-flash",
            temperature=0.6,
            max_tokens=4096,
        )
        router = llm_router or (llm if isinstance(llm, LlmRouter) else None)
        super().__init__(
            agent=synth_agent,
            llm_router=router,
            session_factory=session_factory,
            db=db,
            **kwargs,
        )
        self.brand_profile = brand_profile
        self.llm = llm or router

    async def run(self, task_ctx: dict[str, Any]) -> AgentResult:
        """Execute 7-section funnel strategy generation with compliance guard and offline HTML."""
        t0 = time.perf_counter()
        raw_products = list(task_ctx.get("products") or [])
        domain = str(task_ctx.get("domain", "general_business")).strip()
        target_audience = str(
            task_ctx.get("target_audience")
            or "Khách hàng tiềm năng quan tâm đến giải pháp chất lượng cao"
        ).strip()
        objective = str(
            task_ctx.get("objective")
            or task_ctx.get("instruction")
            or "Tối ưu hóa hành trình chuyển đổi đa tầng và doanh thu bền vững"
        ).strip()
        llm = task_ctx.get("llm") or self.llm
        extra_secrets = _extract_extra_secrets(task_ctx)

        # 1. Detect domain compliance guard
        context_corpus = f"{domain} {objective} " + " ".join(
            str(p.get("name", "")) + " " + str(p.get("note", ""))
            for p in raw_products
            if isinstance(p, dict)
        )
        compliance_type = _detect_compliance_domain(domain, context_corpus)
        disclaimer = _get_compliance_disclaimer(compliance_type)

        # 2. Sort and classify product tiers
        products = self._classify_products(raw_products)

        # 3. Build or query LLM for 7 structured funnel sections
        sections = await self._generate_7_sections(
            llm=llm,
            domain=domain,
            target_audience=target_audience,
            objective=objective,
            products=products,
            disclaimer=disclaimer,
        )

        # 4. Prepare structured data payload
        structured_data: dict[str, Any] = {
            "funnel_name": f"Chiến lược phễu {domain.replace('_', ' ').title()}",
            "domain": domain,
            "compliance_type": compliance_type or "general",
            "compliance_disclaimer": disclaimer,
            "target_audience": target_audience,
            "objective": objective,
            "products": products,
            "sections": sections,
            "created_at": datetime.now(timezone.utc).isoformat(),
        }

        # 5. Render offline HTML and Markdown artifacts
        raw_html = self._render_funnel_html(
            title=f"Chiến Lược Phễu Bán Hàng: {domain.replace('_', ' ').title()}",
            domain=domain,
            compliance_disclaimer=disclaimer,
            sections=sections,
            products=products,
            target_audience=target_audience,
            objective=objective,
        )
        sanitized_html, _ = sanitize_offline_html(raw_html)
        masked_html = mask_secrets(sanitized_html, extra_secrets=extra_secrets)

        md_content = self._render_funnel_markdown(
            title=f"Chiến Lược Phễu Bán Hàng: {domain.replace('_', ' ').title()}",
            domain=domain,
            compliance_disclaimer=disclaimer,
            sections=sections,
            products=products,
        )
        masked_md = mask_secrets(md_content, extra_secrets=extra_secrets)

        html_artifact = ArtifactOutput(
            filename="funnel_strategy.html",
            content=str(masked_html),
            artifact_type="html",
            title=f"Chiến Lược Phễu {domain.replace('_', ' ').title()}",
            metadata={"sections_count": len(sections), "domain": domain},
        )
        md_artifact = ArtifactOutput(
            filename="funnel_strategy.md",
            content=str(masked_md),
            artifact_type="markdown",
            title=f"Bản thảo Markdown Phễu {domain}",
            metadata={"sections_count": len(sections), "domain": domain},
        )

        # Mask secrets across structured data
        masked_structured_data = mask_secrets(
            structured_data, extra_secrets=extra_secrets
        )
        duration_ms = max(1, int((time.perf_counter() - t0) * 1000))

        return AgentResult(
            subtask_id=str(task_ctx.get("subtask_id", "funnel_strategy")),
            agent_id=self.agent.id,
            status="completed",
            output=masked_structured_data,
            content=(
                f"Đã xây dựng thành công chiến lược phễu 7 tầng cho lĩnh vực '{domain}'. "
                f"Tuân thủ chính sách: {disclaimer[:80]}..."
            ),
            structured_data=masked_structured_data,
            artifacts=[html_artifact, md_artifact],
            duration_ms=duration_ms,
        )

    async def execute(
        self,
        subtask: Any,
        context: Optional[dict[str, Any]] = None,
        db_session_factory: Optional[Any] = None,
    ) -> WorkerResult:
        """Adapter method for BaseWorkerAgent orchestrator dispatch."""
        ctx = dict(context or {})
        task_ctx: dict[str, Any] = {}
        if isinstance(subtask, dict):
            task_ctx.update(subtask.get("metadata") or {})
            task_ctx.setdefault("objective", subtask.get("instruction", ""))
            task_ctx["subtask_id"] = subtask.get("id", "subtask")
        else:
            meta = getattr(subtask, "metadata", None) or {}
            task_ctx.update(meta)
            task_ctx.setdefault("objective", getattr(subtask, "instruction", ""))
            task_ctx["subtask_id"] = getattr(subtask, "id", "subtask")

        task_ctx.update(ctx)
        return await self.run(task_ctx)

    def _classify_products(self, raw_products: list[Any]) -> list[dict[str, Any]]:
        """Normalize, sanitize, and sort products by price into funnel tiers."""
        normalized: list[dict[str, Any]] = []
        for idx, item in enumerate(raw_products):
            if isinstance(item, dict):
                p_copy = dict(item)
                name = str(p_copy.get("name") or f"Sản phẩm {idx + 1}")
                price = _parse_numeric_price(p_copy.get("price"))
                p_copy["name"] = name
                p_copy["price"] = price
                p_copy["formatted_price"] = _format_currency(price)
                normalized.append(p_copy)
            elif isinstance(item, str):
                normalized.append(
                    {
                        "name": item,
                        "price": 0.0,
                        "formatted_price": "Miễn phí",
                    }
                )

        # Sort products ascending by price
        normalized.sort(key=lambda x: x.get("price", 0.0))
        return normalized

