def _extract_extra_secrets(task_ctx: dict[str, Any]) -> list[str]:
    """Collect API keys, tokens, and sensitive strings from task context for redaction."""
    extra_secrets: list[str] = list(task_ctx.get("extra_secrets") or [])
    for k, v in task_ctx.items():
        k_lower = k.lower()
        if k_lower in {"author", "title", "subject", "domain", "topic"}:
            continue
        if any(
            term in k_lower
            for term in (
                "key",
                "token",
                "secret",
                "pwd",
                "passwd",
                "password",
                "bearer",
            )
        ) or k_lower.startswith("auth_") or k_lower in {"auth", "authorization"}:
            if isinstance(v, str) and len(v) >= 4:
                extra_secrets.append(v)
    return extra_secrets


def _parse_numeric_price(val: Any) -> float:
    """Safely parse numbers, currency strings (VND, đ, k), or malformed inputs into float."""
    if val is None:
        return 0.0
    if isinstance(val, (int, float)):
        return float(val)
    if not isinstance(val, str):
        try:
            return float(val)
        except (ValueError, TypeError):
            return 0.0

    s = val.strip()
    if not s:
        return 0.0

    # Handle suffix "K" / "k" (e.g. 200k, 200K)
    if s.lower().endswith("k"):
        num_clean = re.sub(r"[^\d.,]", "", s[:-1])
        try:
            return float(num_clean.replace(".", "").replace(",", ".")) * 1000.0
        except (ValueError, TypeError):
            pass

    # Strip currency symbols and whitespace
    s = re.sub(r"[₫đĐVNDvnd\s]", "", s)
    if not s:
        return 0.0

    if "." in s and "," in s:
        # e.g. 200.000,50 -> 200000.50
        s = s.replace(".", "").replace(",", ".")
    elif "." in s:
        parts = s.split(".")
        if len(parts) > 1 and all(len(p) == 3 for p in parts[1:]):
            s = s.replace(".", "")
    elif "," in s:
        parts = s.split(",")
        if len(parts) > 1 and all(len(p) == 3 for p in parts[1:]):
            s = s.replace(",", "")
        else:
            s = s.replace(",", ".")

    try:
        clean_num = re.sub(r"[^\d.]", "", s)
        return float(clean_num) if clean_num else 0.0
    except (ValueError, TypeError):
        return 0.0


def _format_currency(amount: Any) -> str:
    """Format numeric values as Vietnamese Dong currency string."""
    try:
        val = _parse_numeric_price(amount)
        return f"{val:,.0f} ₫".replace(",", ".")
    except (ValueError, TypeError):
        return str(amount) if amount is not None else "0 ₫"


async def _invoke_llm(
    llm: Any,
    messages: list[dict[str, Any]],
    agent: Optional[Agent] = None,
    temperature: float = 0.7,
    max_tokens: int = 4096,
) -> Optional[str]:
    """Safely invoke LLM Router, MockLlm, or callable."""
    if llm is None:
        return None
    try:
        if hasattr(llm, "complete") and callable(llm.complete):
            resp = await llm.complete(
                messages=messages,
                agent=agent,
                temperature=temperature,
                max_tokens=max_tokens,
            )
            if hasattr(resp, "content"):
                return str(resp.content)
            if isinstance(resp, dict):
                return str(resp.get("content", ""))
            return str(resp)

        if callable(llm):
            raw = llm(messages)
            if asyncio.iscoroutine(raw):
                raw = await raw
            if hasattr(raw, "content"):
                return str(raw.content)
            return str(raw)

        return None
    except Exception as exc:
        logger.warning("Error invoking LLM in funnels agent: %s", exc, exc_info=True)
        return None


