    async def execute(
        self,
        subtask: Any,
        context: Optional[dict[str, Any]] = None,
        db_session_factory: Optional[Any] = None,
    ) -> WorkerResult:
        """Adapter method for BaseWorkerAgent orchestrator dispatch."""
        ctx = dict(context or {})
        task_ctx: dict[str, Any] = {}
        if isinstance(subtask, dict):
            task_ctx.update(subtask.get("metadata") or {})
            task_ctx.setdefault("objective", subtask.get("instruction", ""))
            task_ctx["subtask_id"] = subtask.get("id", "subtask")
        else:
            meta = getattr(subtask, "metadata", None) or {}
            task_ctx.update(meta)
            task_ctx.setdefault("objective", getattr(subtask, "instruction", ""))
            task_ctx["subtask_id"] = getattr(subtask, "id", "subtask")

        task_ctx.update(ctx)
        return await self.run(task_ctx)

    def _compute_metrics(self, m: dict[str, Any]) -> dict[str, Any]:
        """Compute key conversion rates and financial efficiency ratios."""
        traffic = float(m.get("traffic") or m.get("visitors") or 0.0)
        leads = float(m.get("leads") or m.get("lead_magnet_optins") or 0.0)
        low_ticket = float(
            m.get("low_ticket_sales")
            or m.get("tripwire_sales")
            or m.get("sales")
            or 0.0
        )
        mid_ticket = float(m.get("mid_ticket_sales") or m.get("core_sales") or 0.0)
        high_ticket = float(m.get("high_ticket_sales") or 0.0)
        ad_spend = float(m.get("ad_spend") or 0.0)
        revenue = float(m.get("revenue") or 0.0)

        optin_rate = round(leads / traffic, 4) if traffic > 0 else 0.0
        low_ticket_cvr = round(low_ticket / leads, 4) if leads > 0 else 0.0
        mid_ticket_cvr = round(mid_ticket / low_ticket, 4) if low_ticket > 0 else 0.0
        high_ticket_cvr = round(high_ticket / mid_ticket, 4) if mid_ticket > 0 else 0.0

        total_customers = low_ticket + mid_ticket + high_ticket
        cac = round(ad_spend / total_customers, 2) if total_customers > 0 else 0.0
        roas = round(revenue / ad_spend, 2) if ad_spend > 0 else 0.0

        return {
            "traffic": int(traffic),
            "leads": int(leads),
            "low_ticket_sales": int(low_ticket),
            "mid_ticket_sales": int(mid_ticket),
            "high_ticket_sales": int(high_ticket),
            "ad_spend": ad_spend,
            "revenue": revenue,
            "optin_rate": optin_rate,
            "low_ticket_cvr": low_ticket_cvr,
            "mid_ticket_cvr": mid_ticket_cvr,
            "high_ticket_cvr": high_ticket_cvr,
            "cac": cac,
            "roas": roas,
        }

