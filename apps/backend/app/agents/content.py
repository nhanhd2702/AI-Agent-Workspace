@dataclass
class ArtifactOutput:
    """Output artifact generated by a worker agent."""

    filename: str
    content: str
    artifact_type: str = "html"
    title: Optional[str] = None
    metadata: dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass
class AgentResult(WorkerResult):
    """Execution result returned by content and research agents.

    Subclasses WorkerResult to maintain full compatibility with BaseWorkerAgent
    and orchestrator dispatchers while exposing structured_data and artifacts.
    """

    structured_data: dict[str, Any] = field(default_factory=dict)
    artifacts: list[ArtifactOutput] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        base_dict = super().to_dict()
        base_dict["structured_data"] = self.structured_data
        base_dict["artifacts"] = [a.to_dict() for a in self.artifacts]
        return base_dict


