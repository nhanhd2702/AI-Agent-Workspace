class DeepResearcherAgent(BaseWorkerAgent):
    """Agent that performs in-depth YouTube and web research, generating offline report decks."""

    def __init__(
        self,
        agent: Optional[Agent] = None,
        yt_client: Optional[YouTubeClient] = None,
        browser: Optional[BrowserController] = None,
        llm: Optional[Any] = None,
        llm_router: Optional[LlmRouter] = None,
        session_factory: Optional[Any] = None,
        db: Optional[Any] = None,
        **kwargs: Any,
    ) -> None:
        synth_agent = agent or Agent(
            id="agent-deep-researcher",
            name="deep_researcher",
            display_name="Deep Researcher",
            role="researcher",
            default_model="gemini-2.5-flash",
            temperature=0.3,
            max_tokens=4096,
        )
        router = llm_router or (llm if isinstance(llm, LlmRouter) else None)
        super().__init__(
            agent=synth_agent,
            llm_router=router,
            session_factory=session_factory,
            db=db,
            **kwargs,
        )
        self.yt_client = yt_client
        self.browser = browser
        self.llm = llm or router

    async def run(self, task_ctx: dict[str, Any]) -> AgentResult:
        """Run deep research on given YouTube channels and web URLs."""
        t0 = time.perf_counter()
        channels = task_ctx.get("channels") or []
        if isinstance(channels, str):
            channels = [channels]
        urls = task_ctx.get("urls") or []
        if isinstance(urls, str):
            urls = [urls]

        min_views = int(task_ctx.get("min_views", 0))
        limit = int(task_ctx.get("limit", 20))
        topic = str(task_ctx.get("topic", "")).strip()

        # Collect secrets for automatic redaction
        extra_secrets: list[str] = list(task_ctx.get("extra_secrets") or [])
        for k, v in task_ctx.items():
            if any(term in k.lower() for term in ("key", "token", "secret", "auth", "pwd")):
                if isinstance(v, str) and len(v) >= 6:
                    extra_secrets.append(v)

        yt = task_ctx.get("yt_client") or self.yt_client
        browser = task_ctx.get("browser") or self.browser
        llm = task_ctx.get("llm") or self.llm

        # 1. Web research via BrowserController (if URLs provided)
        web_findings: list[dict[str, Any]] = []
        if urls and browser is not None:
            for url in urls:
                try:
                    res: BrowserActionResult = await browser.navigate(url)
                    if (
                        getattr(res, "status", None)
                        == BrowserGateStatus.CAPTCHA_REQUIRED.value
                        or getattr(res, "status", None) == "CAPTCHA_REQUIRED"
                    ):
                        duration_ms = max(1, int((time.perf_counter() - t0) * 1000))
                        return AgentResult(
                            subtask_id=str(task_ctx.get("subtask_id", "research")),
                            agent_id=self.agent.id,
                            status="halted",
                            error=(
                                f"CAPTCHA_REQUIRED: {res.message or 'Automated execution halted: captcha gate detected. Human intervention required.'}"
                            ),
                            structured_data={
                                "gate": "CAPTCHA_REQUIRED",
                                "url": url,
                                "details": res.to_dict() if hasattr(res, "to_dict") else {},
                            },
                            duration_ms=duration_ms,
                        )
                    web_findings.append(
                        {
                            "url": url,
                            "title": getattr(res, "title", ""),
                            "content_excerpt": (
                                getattr(res, "content", "")[:500]
                                if getattr(res, "content", None)
                                else ""
                            ),
                        }
                    )
                except Exception as exc:
                    web_findings.append({"url": url, "error": str(exc)})

        # 2. YouTube Channel Video & Transcript Indexing
        verified_videos: list[dict[str, Any]] = []
        if channels and yt is not None:
            for ch_url in channels:
                try:
                    fetched_metas = yt.fetch_channel_videos(
                        ch_url, min_views=min_views, limit=limit
                    )
                    for meta in fetched_metas:
                        t_res: TranscriptResult = yt.fetch_transcript(meta.video_id)
                        is_avail = bool(t_res.available)
                        note = t_res.note or ("" if is_avail else "Không đọc được phụ đề")
                        verified_videos.append(
                            {
                                "video_id": meta.video_id,
                                "title": meta.title,
                                "url": meta.url,
                                "view_count": meta.view_count,
                                "thumbnail_url": meta.thumbnail_url,
                                "channel_title": meta.channel_title or ch_url,
                                "transcript_available": is_avail,
                                "transcript_text": t_res.text if is_avail else "",
                                "transcript_note": note,
                            }
                        )
                except Exception as exc:
                    pass

        # 3. Generate 5 Localized Vietnamese Ideas
        ideas: list[str] = await self._generate_vietnamese_ideas(
            llm=llm,
            topic=topic,
            videos=verified_videos,
            web_findings=web_findings,
        )

        # 4. Build Self-Contained Offline HTML Report Card Deck
        raw_html = self._build_report_html(
            topic=topic,
            channels=channels,
            videos=verified_videos,
            ideas=ideas,
            web_findings=web_findings,
        )

        sanitized_html, _ = sanitize_offline_html(raw_html)
        masked_html = mask_secrets(sanitized_html, extra_secrets=extra_secrets)

        html_artifact = ArtifactOutput(
            filename=f"research_report_{int(time.time())}.html",
            content=str(masked_html),
            artifact_type="html",
            title=f"Báo cáo Nghiên cứu: {topic or 'Tổng hợp nội dung'}",
            metadata={"video_count": len(verified_videos), "idea_count": len(ideas)},
        )

        duration_ms = max(1, int((time.perf_counter() - t0) * 1000))
        structured_data = {
            "topic": mask_secrets(topic, extra_secrets=extra_secrets),
            "channels": mask_secrets(channels, extra_secrets=extra_secrets),
            "videos": mask_secrets(verified_videos, extra_secrets=extra_secrets),
            "ideas": mask_secrets(ideas, extra_secrets=extra_secrets),
            "web_findings": mask_secrets(web_findings, extra_secrets=extra_secrets),
            "total_videos": len(verified_videos),
        }

        return AgentResult(
            subtask_id=str(task_ctx.get("subtask_id", "research")),
            agent_id=self.agent.id,
            status="completed",
            output={
                "video_count": len(verified_videos),
                "ideas_count": len(ideas),
                "html_file": html_artifact.filename,
            },
            content=str(
                mask_secrets(
                    f"Đã hoàn thành nghiên cứu cho chủ đề '{topic}': phân tích {len(verified_videos)} video đã xác thực và sinh 5 ý tưởng nội dung Việt hóa.",
                    extra_secrets=extra_secrets,
                )
            ),
            structured_data=structured_data,
            artifacts=[html_artifact],
            duration_ms=duration_ms,
        )

    async def execute(
        self,
        subtask: Any,
        context: Optional[dict[str, Any]] = None,
        db_session_factory: Optional[Any] = None,
    ) -> WorkerResult:
        """Adapter method for BaseWorkerAgent orchestrator dispatch."""
        ctx = dict(context or {})
        task_ctx: dict[str, Any] = {}
        if isinstance(subtask, dict):
            task_ctx.update(subtask.get("metadata") or {})
            task_ctx.setdefault("topic", subtask.get("instruction", ""))
            task_ctx["subtask_id"] = subtask.get("id", "subtask")
        else:
            meta = getattr(subtask, "metadata", None) or {}
            task_ctx.update(meta)
            task_ctx.setdefault("topic", getattr(subtask, "instruction", ""))
            task_ctx["subtask_id"] = getattr(subtask, "id", "subtask")

        task_ctx.update(ctx)
        return await self.run(task_ctx)

    async def _generate_vietnamese_ideas(
        self,
        llm: Any,
        topic: str,
        videos: list[dict[str, Any]],
        web_findings: list[dict[str, Any]],
    ) -> list[str]:
        """Generate exactly 5 localized Vietnamese ideas via LLM or deterministic fallback."""
        ideas: list[str] = []

        if llm is not None:
            video_summary = "\n".join(
                f"- {v['title']} ({v['view_count']:,} views)" for v in videos[:5]
            )
            messages = [
                {
                    "role": "system",
                    "content": (
                        "Bạn là chuyên gia nghiên cứu nội dung và cố vấn chiến lược sáng tạo tại Việt Nam. "
                        "Nhiệm vụ: Dựa trên các video và dữ liệu thực tế đã xác thực, hãy đưa ra đúng 5 ý tưởng nội dung "
                        "Việt hóa (localized), thực tế, bám sát hành vi người dùng Việt Nam. "
                        "Trả về JSON định dạng: {\"ideas\": [\"ý tưởng 1\", \"ý tưởng 2\", \"ý tưởng 3\", \"ý tưởng 4\", \"ý tưởng 5\"]}"
                    ),
                },
                {
                    "role": "user",
                    "content": (
                        f"Chủ đề: {topic}\n"
                        f"Dữ liệu video thực tế đã xác thực:\n{video_summary or 'Chưa có video'}\n"
                        "Hãy xuất 5 ý tưởng nội dung tiếng Việt."
                    ),
                },
            ]
            raw_content = await _invoke_llm(llm, messages, agent=self.agent)
            if raw_content:
                try:
                    # Look for JSON in response
                    match = re.search(r"\{.*\}", raw_content, re.DOTALL)
                    if match:
                        parsed = json.loads(match.group(0))
                        candidate_ideas = parsed.get("ideas")
                        if isinstance(candidate_ideas, list):
                            for item in candidate_ideas:
                                text = str(item.get("title", item) if isinstance(item, dict) else item).strip()
                                if text:
                                    ideas.append(text)
                except Exception:
                    # Line-based fallback extraction
                    for line in raw_content.splitlines():
                        line_clean = re.sub(r"^[\d\.\-\*\s]+", "", line).strip()
                        if line_clean and len(line_clean) > 8:
                            ideas.append(line_clean)

        # Fallback deterministic derivation to guarantee strictly 5 localized ideas
        if len(ideas) < 5:
            base_anchor = (
                videos[0]["title"]
                if videos
                else (topic if topic else "Chiến lược nội dung")
            )
            clean_anchor = re.sub(r"[^\w\s\d\-_]", "", base_anchor).strip()

            fallback_templates = [
                f"Ứng dụng {clean_anchor} cho thị trường Việt Nam: Tối ưu 3 giây đầu giữ chân khán giả",
                f"Bí quyết chuyển đổi từ {clean_anchor}: Xây dựng thông điệp bán hàng thực chiến",
                f"Phân tích case study {clean_anchor}: 3 bài học đắt giá cho người kinh doanh",
                f"Sai lầm thường gặp khi áp dụng {clean_anchor} và phương pháp giải quyết tối ưu",
                f"Kế hoạch phân phối đa kênh và nhân bản nội dung lấy cảm hứng từ {clean_anchor}",
            ]
            for tpl in fallback_templates:
                if len(ideas) >= 5:
                    break
                if tpl not in ideas:
                    ideas.append(tpl)

        return ideas[:5]

