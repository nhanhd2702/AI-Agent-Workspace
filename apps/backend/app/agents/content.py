class ContentWriterAgent(BaseWorkerAgent):
    """Agent that produces grounded copy with brand guidelines, hook variants, and legal disclaimers."""

    def __init__(
        self,
        agent: Optional[Agent] = None,
        llm: Optional[Any] = None,
        llm_router: Optional[LlmRouter] = None,
        brand_profile: Optional[BrandProfile | dict[str, Any]] = None,
        session_factory: Optional[Any] = None,
        db: Optional[Any] = None,
        **kwargs: Any,
    ) -> None:
        synth_agent = agent or Agent(
            id="agent-content-writer",
            name="content_writer",
            display_name="Content Writer",
            role="copywriter",
            default_model="gemini-2.5-flash",
            temperature=0.7,
            max_tokens=4096,
        )
        router = llm_router or (llm if isinstance(llm, LlmRouter) else None)
        super().__init__(
            agent=synth_agent,
            llm_router=router,
            session_factory=session_factory,
            db=db,
            **kwargs,
        )
        self.brand_profile = brand_profile
        self.llm = llm or router

    async def run(self, task_ctx: dict[str, Any]) -> AgentResult:
        """Run content generation with brand tone, 3+ hooks, and legal disclaimer."""
        t0 = time.perf_counter()
        topic = str(task_ctx.get("topic", "")).strip()
        channel = str(
            task_ctx.get("channel") or task_ctx.get("platform") or "Facebook"
        ).strip()
        forbidden_terms = list(task_ctx.get("forbidden_terms") or [])
        raw_brand = task_ctx.get("brand_profile") or self.brand_profile
        llm = task_ctx.get("llm") or self.llm

        # Collect secrets for automatic redaction
        extra_secrets: list[str] = list(task_ctx.get("extra_secrets") or [])
        for k, v in task_ctx.items():
            if any(term in k.lower() for term in ("key", "token", "secret", "auth", "pwd")):
                if isinstance(v, str) and len(v) >= 6:
                    extra_secrets.append(v)

        # 1. Resolve BrandProfile
        brand_data = self._resolve_brand_profile(raw_brand)

        # 2. Build structured LLM Prompt
        hooks, body, cta, disclaimer = await self._generate_copy(
            llm=llm,
            topic=topic,
            channel=channel,
            brand_data=brand_data,
            forbidden_terms=forbidden_terms,
        )

        # 3. Post-process: Filter forbidden terms & enforce legal boundaries
        hooks = [self._enforce_forbidden_terms(h, forbidden_terms) for h in hooks]
        body = self._enforce_forbidden_terms(body, forbidden_terms)
        cta = self._enforce_forbidden_terms(cta, forbidden_terms)

        legal_boundary = brand_data.get("legal_boundaries")
        if legal_boundary and legal_boundary not in disclaimer:
            disclaimer = f"{disclaimer} (Lưu ý tuân thủ: {legal_boundary})".strip()

        # 4. Create Markdown and HTML Draft Artifacts with Secret Redaction
        md_content = self._render_markdown_artifact(
            topic=topic,
            channel=channel,
            brand_name=brand_data.get("brand_name", ""),
            hooks=hooks,
            body=body,
            cta=cta,
            disclaimer=disclaimer,
        )
        masked_md = mask_secrets(md_content, extra_secrets=extra_secrets)

        raw_html = self._render_html_artifact(
            topic=topic,
            channel=channel,
            brand_name=brand_data.get("brand_name", ""),
            hooks=hooks,
            body=body,
            cta=cta,
            disclaimer=disclaimer,
        )
        sanitized_html, _ = sanitize_offline_html(raw_html)
        masked_html = mask_secrets(sanitized_html, extra_secrets=extra_secrets)

        ts = int(time.time())
        md_artifact = ArtifactOutput(
            filename=f"post_draft_{ts}.md",
            content=str(masked_md),
            artifact_type="markdown",
            title=f"Bản thảo nội dung: {topic}",
        )
        html_artifact = ArtifactOutput(
            filename=f"post_draft_{ts}.html",
            content=str(masked_html),
            artifact_type="html",
            title=f"Xem trước nội dung: {topic}",
        )

        duration_ms = max(1, int((time.perf_counter() - t0) * 1000))
        structured_data = {
            "topic": topic,
            "channel": channel,
            "brand_profile": brand_data,
            "hooks": [mask_secrets(h, extra_secrets=extra_secrets) for h in hooks],
            "body": mask_secrets(body, extra_secrets=extra_secrets),
            "cta": mask_secrets(cta, extra_secrets=extra_secrets),
            "disclaimer": mask_secrets(disclaimer, extra_secrets=extra_secrets),
            "legal_disclaimer": mask_secrets(disclaimer, extra_secrets=extra_secrets),
        }

        return AgentResult(
            subtask_id=str(task_ctx.get("subtask_id", "copywriting")),
            agent_id=self.agent.id,
            status="completed",
            output={
                "topic": topic,
                "hook_count": len(hooks),
                "artifacts": [md_artifact.filename, html_artifact.filename],
            },
            content=str(mask_secrets(body, extra_secrets=extra_secrets)),
            structured_data=structured_data,
            artifacts=[md_artifact, html_artifact],
            duration_ms=duration_ms,
        )

    async def execute(
        self,
        subtask: Any,
        context: Optional[dict[str, Any]] = None,
        db_session_factory: Optional[Any] = None,
    ) -> WorkerResult:
        """Adapter method for BaseWorkerAgent orchestrator dispatch."""
        ctx = dict(context or {})
        task_ctx: dict[str, Any] = {}
        if isinstance(subtask, dict):
            task_ctx.update(subtask.get("metadata") or {})
            task_ctx.setdefault("topic", subtask.get("instruction", ""))
            task_ctx["subtask_id"] = subtask.get("id", "subtask")
        else:
            meta = getattr(subtask, "metadata", None) or {}
            task_ctx.update(meta)
            task_ctx.setdefault("topic", getattr(subtask, "instruction", ""))
            task_ctx["subtask_id"] = getattr(subtask, "id", "subtask")

        task_ctx.update(ctx)
        return await self.run(task_ctx)

    def _resolve_brand_profile(
        self, raw_brand: Optional[BrandProfile | dict[str, Any]]
    ) -> dict[str, Any]:
        """Extract brand profile fields into normalized dictionary."""
        if not raw_brand:
            return {
                "brand_name": "Thương hiệu chuẩn mực",
                "tone_of_voice": "Chuyên nghiệp, chân thành, hữu ích",
                "target_audience": "Người tiêu dùng hiện đại",
                "legal_boundaries": "Tuân thủ nghiêm ngặt tính xác thực và pháp luật",
            }

        if isinstance(raw_brand, dict):
            return {
                "brand_name": raw_brand.get("brand_name", "Thương hiệu"),
                "tone_of_voice": raw_brand.get("tone_of_voice", "Chuyên nghiệp"),
                "target_audience": raw_brand.get("target_audience", "Đại chúng"),
                "legal_boundaries": raw_brand.get("legal_boundaries", ""),
                "brand_colors": raw_brand.get("brand_colors", []),
                "fonts": raw_brand.get("fonts", []),
            }

        if isinstance(raw_brand, BrandProfile):
            return {
                "brand_name": raw_brand.brand_name,
                "tone_of_voice": raw_brand.tone_of_voice or "Chuyên nghiệp",
                "target_audience": raw_brand.target_audience or "Đại chúng",
                "legal_boundaries": raw_brand.legal_boundaries or "",
                "brand_colors": raw_brand.brand_colors or [],
                "fonts": raw_brand.fonts or [],
            }

        return {}

    def _enforce_forbidden_terms(self, text: str, forbidden_terms: list[str]) -> str:
        """Sanitize or redact forbidden terms from text."""
        sanitized = text
        for term in forbidden_terms:
            if not term:
                continue
            pattern = re.compile(re.escape(term), re.IGNORECASE)
            sanitized = pattern.sub("[từ bị hạn chế]", sanitized)
        return sanitized

    async def _generate_copy(
        self,
        llm: Any,
        topic: str,
        channel: str,
        brand_data: dict[str, Any],
        forbidden_terms: list[str],
    ) -> tuple[list[str], str, str, str]:
        """Generate at least 3 hooks, body, cta, and disclaimer via LLM or deterministic fallback."""
        hooks: list[str] = []
        body: str = ""
        cta: str = ""
        disclaimer: str = ""

        if llm is not None:
            brand_context = (
                f"Thương hiệu: {brand_data.get('brand_name')}\n"
                f"Giọng điệu (Tone): {brand_data.get('tone_of_voice')}\n"
                f"Khán giả mục tiêu: {brand_data.get('target_audience')}\n"
                f"Ranh giới pháp lý / Lưu ý: {brand_data.get('legal_boundaries')}\n"
                f"Từ cấm tuyệt đối: {', '.join(forbidden_terms) if forbidden_terms else 'Không có'}"
            )
            messages = [
                {
                    "role": "system",
                    "content": (
                        "Bạn là Senior Copywriter chuyên nghiệp tuân thủ nghiêm ngặt căn cứ thực tế và pháp lý. "
                        "Quy tắc bất di bất dịch: KHÔNG bịa đặt số liệu thống kê hoặc trích dẫn sai sự thật. "
                        f"Thông tin thương hiệu bắt buộc:\n{brand_context}\n"
                        "Xuất kết quả đúng định dạng JSON:\n"
                        "{\n"
                        '  "hooks": ["hook 1", "hook 2", "hook 3"],\n'
                        '  "body": "Nội dung bài viết đầy đủ...",\n'
                        '  "cta": "Lời kêu gọi hành động...",\n'
                        '  "disclaimer": "Tuyên bố miễn trừ trách nhiệm pháp lý rõ ràng..."\n'
                        "}"
                    ),
                },
                {
                    "role": "user",
                    "content": (
                        f"Chủ đề: {topic}\n"
                        f"Kênh phân phối: {channel}\n"
                        "Hãy viết bài theo đúng giọng điệu thương hiệu với ít nhất 3 biến thể hook và tuyên bố từ chối trách nhiệm phù hợp."
                    ),
                },
            ]

            raw = await _invoke_llm(llm, messages, agent=self.agent)
            if raw:
                try:
                    match = re.search(r"\{.*\}", raw, re.DOTALL)
                    if match:
                        parsed = json.loads(match.group(0))
                        parsed_hooks = parsed.get("hooks")
                        if isinstance(parsed_hooks, list):
                            hooks = [str(h).strip() for h in parsed_hooks if str(h).strip()]
                        body = str(parsed.get("body", "")).strip()
                        cta = str(parsed.get("cta", "")).strip()
                        disclaimer = str(parsed.get("disclaimer", "")).strip()
                except Exception:
                    pass

        # Fallback enforcement for 3+ hooks
        if len(hooks) < 3:
            fallback_hooks = [
                f"Bật mí bí quyết {topic or 'thư giãn'} hiệu quả dành riêng cho bạn",
                f"Đừng bỏ qua điều này nếu bạn muốn làm chủ {topic or 'cuộc sống'}!",
                f"3 điều đơn giản giúp tối ưu trải nghiệm {topic or 'hằng ngày'} ngay hôm nay",
            ]
            for h in fallback_hooks:
                if len(hooks) >= 3:
                    break
                if h not in hooks:
                    hooks.append(h)

        if not body:
            body = (
                f"Trong nhịp sống bận rộn hiện đại, việc dành thời gian cho {topic or 'bản thân'} là điều vô cùng quý giá. "
                f"Theo định hướng từ {brand_data.get('brand_name', 'chúng tôi')}, việc chăm chút từng khoảnh khắc nhỏ "
                "sẽ mang đến nguồn năng lượng an yên, tái tạo tinh thần và nâng tầm chất lượng sống mỗi ngày."
            )

        if not cta:
            cta = f"Hãy để lại bình luận hoặc nhắn tin cho {brand_data.get('brand_name', 'chúng tôi')} để nhận thêm thông tin chi tiết!"

        if not disclaimer:
            legal_b = brand_data.get("legal_boundaries", "")
            disclaimer = (
                f"Lưu ý: Nội dung chia sẻ dựa trên trải nghiệm thực tế và kiến thức tham khảo, không thay thế cho tư vấn y tế, pháp lý hoặc chuyên môn cá nhân. "
                f"{legal_b}".strip()
            )

        return hooks, body, cta, disclaimer

