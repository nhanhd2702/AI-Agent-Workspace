def _sanitize_href(url: Optional[str]) -> str:
    """Validate and sanitize URL for safe HTML href attribute usage (prevent XSS/javascript:)."""
    if not url or not isinstance(url, str):
        return "#"
    cleaned = url.strip()
    parsed = urlparse(cleaned)
    if parsed.scheme.lower() not in {"http", "https"}:
        return "#"
    return html.escape(cleaned, quote=True)


def _safe_text(text: Any) -> str:
    """Escape text for safe HTML interpolation."""
    if text is None:
        return ""
    return html.escape(str(text), quote=True)


async def _invoke_llm(
    llm: Any,
    messages: list[dict[str, Any]],
    agent: Optional[Agent] = None,
    temperature: float = 0.7,
    max_tokens: int = 4096,
) -> Optional[str]:
    """Safely invoke an LLM Router, MockLlm, or callable."""
    if llm is None:
        return None

    try:
        if hasattr(llm, "complete") and callable(llm.complete):
            resp = await llm.complete(
                messages=messages,
                agent=agent,
                temperature=temperature,
                max_tokens=max_tokens,
            )
            if hasattr(resp, "content"):
                return str(resp.content)
            if isinstance(resp, dict):
                return str(resp.get("content", ""))
            return str(resp)

        if callable(llm):
            raw = llm(messages)
            if asyncio.iscoroutine(raw):
                raw = await raw
            if hasattr(raw, "content"):
                return str(raw.content)
            return str(raw)

        return None
    except Exception as exc:
        logger.warning("Error invoking LLM in content agent: %s", exc, exc_info=True)
        return None


